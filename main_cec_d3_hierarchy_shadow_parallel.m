function main_cec_d3_hierarchy_shadow_parallel
% Gate 1 only: shadow selectors + exact regression, no new optimizer variant.
    root=fileparts(mfilename('fullpath'));
    addpath(root,fullfile(root,'data','cec2017'))
    cd(fullfile(root,'data','cec2017'))
    functionIDs=[3 6 9 12 13 20 28 30]; repeatID=141;
    D=30; N=50; budget=60000; seedBase=20271004;
    stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
    resultDir=fullfile(root,'results','cec',['cec2017_d3_hierarchy_shadow_' stamp]);
    scratch=fullfile(resultDir,'instrumented'); mkdir(scratch)
    source=fileread(fullfile(root,'DSS_RLCSO.m'));
    % Generate a diagnostic copy; do not edit the frozen production source.
    instrumented=BuildAuditCopy(source);
    SaveText(fullfile(scratch,'DSS_RLCSO_Shadow.m'),instrumented);
    addpath(scratch)
    pool=gcp('nocreate');
    if isempty(pool),parpool('local',4);else,assert(pool.NumWorkers==4);end
    records=cell(numel(functionIDs),1); summaries=records; samples=records;
    parfor q=1:numel(functionIDs)
        addpath(root,scratch,fullfile(root,'data','cec2017'))
        cd(fullfile(root,'data','cec2017'))
        [records{q},summaries{q},samples{q}]=RunAudit( ...
            functionIDs(q),repeatID,D,N,budget,seedBase);
        fprintf('Shadow regression F%d passed.\n',functionIDs(q))
    end
    assert(strcmp(source,fileread(fullfile(root,'DSS_RLCSO.m'))))
    writetable(struct2table([records{:}]),fullfile(resultDir,'regression.csv'))
    writetable(struct2table([summaries{:}]),fullfile(resultDir,'shadow_summary.csv'))
    writetable(vertcat(samples{:}),fullfile(resultDir,'shadow_samples.csv'))
    SaveText(fullfile(resultDir,'README.md'),sprintf([ ...
        '# D3 hierarchy selection shadow audit\n\n' ...
        'Gate 1: D30, 60,000 FE, N50, seed 141, F3/F6/F9/F12/F13/F20/F28/F30; four workers.\n\n' ...
        'Original D3 and a generated diagnostic copy run with identical initialization and search seeds. ' ...
        'Every real objective call, complete T, Best, production diagnostic fields and final RNG state must agree. ' ...
        'Shadow selectors do not call Fitness. Baseline and replay each use 60,000 real FE; the audit is not a zero-cost rerun.\n\n' ...
        'All shadow plans use the same already-generated D3 pool and round-start best/center. ' ...
        'They call the production SelectCats, CandidateScreen and GlobalCandidateScreen functions. ' ...
        'Old uses the production ID fallback and a separate, seeded stream to shuffle its two parents. ' ...
        'K2 and K8 use joint Global-Cap2 selection within the production cat shortlist. ' ...
        'Equality/overlap ignore execution ordering but retain both parent ID and candidate ID.\n\n' ...
        'ExplorerFarEvaluatedFrozen measures whether the far-role parent\x27s representative far candidate receives a slot. ' ...
        'PostTrace metrics use the actual D3 best after its Tracing evaluations; they isolate reference drift, ' ...
        'not the complete legacy Seeking execution, which can update best again after its first parent. ' ...
        'The shadow trajectories never execute alternative selections. Results diagnose selection structure, not optimizer quality.\n\n' ...
        'shadow_summary.csv averages every round; shadow_samples.csv retains every 200th round and the final round. ' ...
        'Audit-copy runtimes include logging and extra sorting and must not be interpreted as alternative algorithm costs.\n']));
    fprintf('Saved hierarchy audit: %s\n',resultDir)
end

function [record,summary,sample]=RunAudit(fid,repeat,D,N,budget,seedBase)
    initSeed=seedBase+repeat; searchSeed=initSeed+100000;
    rng(initSeed,'twister'); initial=-100+200*rand(N,D);
    state=struct('lowerBound',-100*ones(1,D),'upperBound',100*ones(1,D), ...
        'maxEvaluations',budget,'initialPopulation',initial, ...
        'actionMode','fixed2','rlMode','modeAwareV41','seekingMode','range', ...
        'seekSelection','globalCap2','searchCore','elite','eliteGuidance',true, ...
        'seekingEliteGuidance',true,'tracingElitistAcceptance',true, ...
        'tracingDecay',true,'virtualTracing',true,'SMP',5,'evaluationQuota',2, ...
        'recoveryEnabled',false,'useModePreserving',true, ...
        'ablation',struct('useCatScreen',true,'useCandidateScreen',true,'useRL',false));
    observedCalls=0;
    [b0,t0,i0]=DSS_RLCSO(@CountedObjective,state,1,N,searchSeed); r0=rng;
    assert(observedCalls==budget); observedCalls=0;
    [b1,t1,i1]=DSS_RLCSO_Shadow(@CountedObjective,state,1,N,searchSeed); r1=rng;
    assert(observedCalls==budget && isequaln(b0,b1) && isequal(t0,t1) && isequal(r0,r1))
    fields=fieldnames(i0);
    for j=1:numel(fields)
        if strcmp(fields{j},'Seconds'),continue,end
        assert(isequaln(i0.(fields{j}),i1.(fields{j})), ...
            'Production field changed: %s',fields{j})
    end
    assert(i1.Evaluations==budget && all(i1.EvaluationsPerRound==5))
    assert(all(i1.ActualTracingEvaluations==2) && all(i1.ActualSeekingEvaluations==3))
    rows=struct2table(i1.HierarchyShadow);
    assert(all(rows.GlobalProductionEqual==1) && all(rows.ProductionPlanExecutedEqual==1))
    names=rows.Properties.VariableNames;
    summary=struct('FunctionID',fid,'Run',repeat,'Rounds',height(rows));
    for j=1:numel(names)
        if strcmp(names{j},'FE'),continue,end
        summary.(names{j})=mean(rows.(names{j}),'omitnan');
    end
    tieFree=rows.AnyDistanceTie==0;
    summary.TieFreeRounds=nnz(tieFree);
    summary.K8MismatchTieFree=nnz(rows.Joint8GlobalEqual(tieFree)==0);
    sample=rows(unique([1:200:height(rows) height(rows)]),:);
    sample=addvars(sample,repmat(fid,height(sample),1), ...
        repmat(repeat,height(sample),1),'Before',1,'NewVariableNames',{'FunctionID','Run'});
    record=struct('FunctionID',fid,'Run',repeat,'InitSeed',initSeed, ...
        'SearchSeed',searchSeed,'Dimension',D,'Evaluations',budget, ...
        'OriginalBestError',max(0,b0.Cost-100*fid),'AuditBestError',max(0,b1.Cost-100*fid), ...
        'CompleteTrajectoryEqual',true,'BestEqual',true,'FinalRNGEqual',true, ...
        'ProductionDiagnosticsEqual',true,'ObjectiveCallsEqual',true, ...
        'OriginalSeconds',i0.Seconds,'AuditSeconds',i1.Seconds);
    function value=CountedObjective(x)
        observedCalls=observedCalls+1;
        value=CEC2017Function(x,fid);
    end
end

function source=BuildAuditCopy(source)
    source=strrep(source,sprintf('\r\n'),sprintf('\n'));
    source=ReplaceOnce(source,'function [Best,T,info] = DSS_RLCSO(', ...
        'function [Best,T,info] = DSS_RLCSO_Shadow(');
    source=ReplaceOnce(source,'    clockStart=tic;',sprintf([ ...
        '    clockStart=tic;\n' ...
        '    auditStream=RandStream(''mt19937ar'',''Seed'',190000+seed);\n' ...
        '    auditRows=cell(ceil(state.maxEvaluations/5),1); auditRound=0;\n' ...
        '    auditSelectors=struct(''Cats'',@SelectCats,''Candidate'',@CandidateScreen,''Global'',@GlobalCandidateScreen);']));
    source=ReplaceOnce(source,'        remaining=budgetThisRound;',sprintf([ ...
        '        assert(modePreserving && globalSelection && targetSeek==3);\n' ...
        '        auditRound=auditRound+1; auditPostChecked=false;\n' ...
        '        [auditRow,auditContext]=D3HierarchyShadow(seekingPool,seekIds,roundBest,center,targetSeek,auditSelectors,auditStream);\n' ...
        '        auditRow.FE=info.Evaluations;\n' ...
        '        auditRow.GlobalProductionEqual=double(isequal(auditContext.GlobalPlan,seekPlan));\n' ...
        '        auditExecuted=cell(sizepop,1);\n' ...
        '        remaining=budgetThisRound;']));
    source=ReplaceOnce(source,'                copies=seekingPool{i};',sprintf([ ...
        '                if ~auditPostChecked\n' ...
        '                    auditRow=D3HierarchyPostTrace(auditRow,auditContext,seekingPool,Best.Vector,center,@CandidateScreen);\n' ...
        '                    auditPostChecked=true;\n' ...
        '                end\n' ...
        '                copies=seekingPool{i};']));
    source=ReplaceOnce(source,'                    value=f(copies(j,:));',sprintf([ ...
        '                    auditExecuted{i}(end+1)=j;\n' ...
        '                    value=f(copies(j,:));']));
    % This point follows all real evaluations of the round.
    marker='        info.SeekingParentCoverage(end+1)=';
    position=strfind(source,marker); assert(numel(position)==1);
    source=[source(1:position-1) sprintf([ ...
        '        auditRow.ProductionPlanExecutedEqual=double(isequal(seekPlan,auditExecuted));\n' ...
        '        auditRows{auditRound}=auditRow;\n']) source(position:end)];
    source=ReplaceOnce(source,'    info.Seconds=toc(clockStart);',sprintf([ ...
        '    info.HierarchyShadow=[auditRows{1:auditRound}];\n' ...
        '    info.Seconds=toc(clockStart);']));
end

function text=ReplaceOnce(text,old,new)
    assert(numel(strfind(text,old))==1,'Audit injection marker is not unique: %s',old)
    text=strrep(text,old,new);
end

function SaveText(path,text)
    file=fopen(path,'w','n','UTF-8'); assert(file>=0)
    cleanup=onCleanup(@()fclose(file)); %#ok<NASGU>
    fprintf(file,'%s',text);
end
