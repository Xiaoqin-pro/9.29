clc
clear
close all

root=fileparts(mfilename('fullpath'));
addpath(root,fullfile(root,'data','cec2017'))
cd(fullfile(root,'data','cec2017'))

functionIDs=[1 10 14 16 19 22 24 27];
repeatIDs=91:93;
quotaValues=[1 2 3];
algorithmNames={'Fixed-T1S4','Fixed-T2S3','Fixed-T3S2'};
D=30;
population=50;
maxEvaluations=60000;
seedBase=20271004;
lb=-100*ones(1,D);
ub=100*ones(1,D);
workerCount=4;
batchSize=4;

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
resultDir=fullfile(root,'results','cec', ...
    ['cec2017_quota_pretest_' stamp]);
mkdir(resultDir);

jobs=struct('FunctionID',{},'Run',{},'InitSeed',{},'SearchSeed',{}, ...
    'InitialPopulation',{},'Quota',{},'Algorithm',{});
count=0;
for mode=1:numel(quotaValues)
    for functionID=functionIDs
        for repeat=repeatIDs
            initSeed=seedBase+repeat;
            rng(initSeed,'twister')
            count=count+1;
            jobs(count)=struct('FunctionID',functionID,'Run',repeat, ...
                'InitSeed',initSeed,'SearchSeed',initSeed+100000, ...
                'InitialPopulation',lb+rand(population,D).*(ub-lb), ...
                'Quota',quotaValues(mode),'Algorithm',algorithmNames{mode});
        end
    end
end

pool=gcp('nocreate');
if isempty(pool)
    parpool('local',workerCount);
elseif pool.NumWorkers~=workerCount
    delete(pool);
    parpool('local',workerCount);
end

records=cell(numel(jobs),1);
for first=1:batchSize:numel(jobs)
    last=min(first+batchSize-1,numel(jobs));
    batch=jobs(first:last);
    batchResults=cell(numel(batch),1);
    parfor j=1:numel(batch)
        job=batch(j);
        f=@(x)CEC2017Function(x,job.FunctionID);
        state=struct('lowerBound',lb,'upperBound',ub, ...
            'maxEvaluations',maxEvaluations,'initialPopulation',job.InitialPopulation, ...
            'actionMode','fixed2','rlMode','modeAwareV41','seekingMode','range', ...
            'seekSelection','globalCap2','searchCore','elite', ...
            'eliteGuidance',true,'seekingEliteGuidance',true, ...
            'tracingElitistAcceptance',true,'tracingDecay',true, ...
            'virtualTracing',true,'SMP',5,'recoveryEnabled',false, ...
            'useModePreserving',true,'evaluationQuota',job.Quota, ...
            'feedbackLogging',true, ...
            'ablation',struct('useCatScreen',true,'useCandidateScreen',true, ...
                'useRL',false));
        [Best,T,info]=DSS_RLCSO(f,state,ceil(maxEvaluations/population), ...
            population,job.SearchSeed);
        assert(info.Evaluations==maxEvaluations && numel(T)==maxEvaluations)
        assert(all(isfinite(T)) && all(info.EvaluationsPerRound==5))
        assert(all(info.ActualTracingEvaluations==job.Quota))
        assert(all(info.ActualSeekingEvaluations==5-job.Quota))
        assert(all(info.BudgetFillRate==1))
        assert(max(abs(info.ModeAllocationError),[],'all')==0)
        assert(max(info.SeekingMaxParentEvaluations)<=2)
        functionValue=100*job.FunctionID;
        batchResults{j}=struct('Function',sprintf('F%02d',job.FunctionID), ...
            'FunctionID',job.FunctionID,'Algorithm',job.Algorithm,'Run',job.Run, ...
            'InitSeed',job.InitSeed,'SearchSeed',job.SearchSeed, ...
            'TracingQuota',job.Quota,'Evaluations',info.Evaluations, ...
            'BestCost',Best.Cost,'BestError',max(0,Best.Cost-functionValue), ...
            'Seconds',info.Seconds,'MeanSeekSuccess',mean(info.FeedbackSeekingSuccess), ...
            'MeanTraceSuccess',mean(info.TracingSuccessHistory), ...
            'MeanSeekGlobalImprovement',mean(info.FeedbackSeekingGlobalImprovement), ...
            'MeanParentCoverage',mean(info.SeekingParentCoverage), ...
            'MeanConcentration',mean(info.SeekingConcentration));
    end
    for j=1:numel(batch)
        records{first+j-1}=batchResults{j};
    end
    writetable(struct2table([records{1:last}]), ...
        fullfile(resultDir,'raw_runs_checkpoint.csv'));
    fprintf('Completed %d/%d runs with %d workers\n', ...
        last,numel(jobs),workerCount);
end

rawRuns=struct2table([records{:}]);
writetable(rawRuns,fullfile(resultDir,'raw_runs.csv'));
summaryRecords={};
for mode=1:numel(quotaValues)
    for functionID=functionIDs
        rows=rawRuns(rawRuns.FunctionID==functionID & ...
            rawRuns.TracingQuota==quotaValues(mode),:);
        summaryRecords{end+1}=struct('Function',sprintf('F%02d',functionID), ...
            'FunctionID',functionID,'Algorithm',algorithmNames{mode}, ...
            'TracingQuota',quotaValues(mode),'SeekingQuota',5-quotaValues(mode), ...
            'Runs',height(rows),'MeanError',mean(rows.BestError), ...
            'StdError',std(rows.BestError),'MedianError',median(rows.BestError), ...
            'MeanSeconds',mean(rows.Seconds),'MeanSeekSuccess',mean(rows.MeanSeekSuccess), ...
            'MeanTraceSuccess',mean(rows.MeanTraceSuccess), ...
            'MeanSeekGlobalImprovement',mean(rows.MeanSeekGlobalImprovement), ...
            'MeanParentCoverage',mean(rows.MeanParentCoverage), ...
            'MeanConcentration',mean(rows.MeanConcentration));
    end
end
writetable(struct2table([summaryRecords{:}]),fullfile(resultDir,'summary.csv'));
readme={ ...
    '# Fixed Seeking/Tracing evaluation-quota pretest at 60k FE', ...
    '', ...
    '- Functions: F1, F10, F14, F16, F19, F22, F24 and F27.', ...
    '- Repeats: 91:93; D=30; population=50; 60,000 FE.', ...
    '- All runs use D3 dynamics, Global-Cap2, Range Seeking, MR=0.4, SMP=5, no Recovery and no RL.', ...
    '- Fixed-T1S4: 1 Tracing + 4 Seeking evaluations per round.', ...
    '- Fixed-T2S3: 2 Tracing + 3 Seeking evaluations per round.', ...
    '- Fixed-T3S2: 3 Tracing + 2 Seeking evaluations per round.', ...
    '- The only changed quantity is the fixed real-evaluation quota; total FE remains 60,000.', ...
    '- The script checks exact FE accounting, per-round quota and parent cap.', ...
    ''};
fid=fopen(fullfile(resultDir,'README.md'),'w');
fprintf(fid,'%s\n',readme{:});
fclose(fid);
delete(gcp('nocreate'))
fprintf('Saved quota pretest to %s\n',resultDir);

function value=CEC2017Function(x,functionID)
    value=cec17_func(x',functionID);
    value=value(1);
end
