clc
clear
close all

root=fileparts(mfilename('fullpath'));
addpath(root,fullfile(root,'data','cec2017'))
cd(fullfile(root,'data','cec2017'))

functionIDs=[3 6 9 12 13 20 28 30];
repeatIDs=61:63;
selectionModes={'globalCap2','matchedRandomCap2'};
eliteModes=[true false];
modeNames={'E','N'};
selectionNames={'G','R'};
D=30;
population=50;
maxEvaluations=60000;
seedBase=20271004;
lb=-100*ones(1,D);
ub=100*ones(1,D);
workerCount=4;
batchSize=4;

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
resultDir=fullfile(root,'results','cec',['cec2017_elite_screen_interaction_' stamp]);
mkdir(resultDir);

jobs=struct('FunctionID',{},'Run',{},'InitSeed',{},'SearchSeed',{}, ...
    'InitialPopulation',{},'Selection',{},'SeekingEliteGuidance',{}, ...
    'Algorithm',{});
count=0;
for eliteMode=1:numel(eliteModes)
    for selectionMode=1:numel(selectionModes)
        for functionID=functionIDs
            for repeat=repeatIDs
                initSeed=seedBase+repeat;
                rng(initSeed,'twister')
                count=count+1;
                algorithm=sprintf('%s-%s',modeNames{eliteMode},selectionNames{selectionMode});
                jobs(count)=struct('FunctionID',functionID,'Run',repeat, ...
                    'InitSeed',initSeed,'SearchSeed',initSeed+100000, ...
                    'InitialPopulation',lb+rand(population,D).*(ub-lb), ...
                    'Selection',selectionModes{selectionMode}, ...
                    'SeekingEliteGuidance',eliteModes(eliteMode), ...
                    'Algorithm',algorithm);
            end
        end
    end
end

pool=gcp('nocreate');
if isempty(pool)
    parpool('local',workerCount);
elseif pool.NumWorkers~=workerCount
    delete(pool);
    parpool('local',workerCount);
end

records=cell(numel(jobs),1);
for first=1:batchSize:numel(jobs)
    last=min(first+batchSize-1,numel(jobs));
    batch=jobs(first:last);
    batchResults=cell(numel(batch),1);
    parfor j=1:numel(batch)
        job=batch(j);
        f=@(x)CEC2017Function(x,job.FunctionID);
        state=struct('lowerBound',lb,'upperBound',ub, ...
            'maxEvaluations',maxEvaluations,'initialPopulation',job.InitialPopulation, ...
            'actionMode','fixed2','rlMode','modeAwareV41','seekingMode','range', ...
            'seekSelection',job.Selection,'searchCore','elite','eliteGuidance',true, ...
            'seekingEliteGuidance',job.SeekingEliteGuidance, ...
            'tracingElitistAcceptance',true,'tracingDecay',true, ...
            'virtualTracing',true,'SMP',5,'recoveryEnabled',false, ...
            'useModePreserving',true,'feedbackLogging',true, ...
            'ablation',struct('useCatScreen',true,'useCandidateScreen',true, ...
                'useRL',false));
        [Best,T,info]=DSS_RLCSO(f,state,ceil(maxEvaluations/population), ...
            population,job.SearchSeed);
        assert(info.Evaluations==maxEvaluations && numel(T)==maxEvaluations)
        assert(all(isfinite(T)) && all(info.EvaluationsPerRound==5))
        assert(all(info.ActualTracingEvaluations==2))
        assert(all(info.ActualSeekingEvaluations==3))
        assert(all(info.BudgetFillRate==1))
        assert(max(abs(info.ModeAllocationError),[],'all')==0)
        assert(max(info.SeekingMaxParentEvaluations)<=2)
        age=info.FeedbackSeekingAgeFE(:);
        success=info.FeedbackSeekingSuccess(:);
        globalImprovement=info.FeedbackSeekingGlobalImprovement(:);
        functionValue=100*job.FunctionID;
        batchResults{j}=struct('Function',sprintf('F%02d',job.FunctionID), ...
            'FunctionID',job.FunctionID,'Algorithm',job.Algorithm, ...
            'Run',job.Run,'InitSeed',job.InitSeed,'SearchSeed',job.SearchSeed, ...
            'SeekingEliteGuidance',job.SeekingEliteGuidance, ...
            'SeekSelection',job.Selection,'Evaluations',info.Evaluations, ...
            'BestCost',Best.Cost,'BestError',max(0,Best.Cost-functionValue), ...
            'Seconds',info.Seconds, ...
            'SeekingSuccessRate',mean(success), ...
            'SeekingGlobalImprovementRate',mean(globalImprovement), ...
            'FeedbackAgeMeanFE',mean(age), ...
            'DistanceToBestMean',mean(info.FeedbackSeekingDistanceToBest), ...
            'DistanceToEliteMean',mean(info.FeedbackSeekingDistanceToElite), ...
            'EliteAlignedFraction',mean(info.FeedbackSeekingDistanceToElite < ...
                info.FeedbackSeekingDistanceToBest), ...
            'MeanParentCoverage',mean(info.SeekingParentCoverage), ...
            'MeanConcentration',mean(info.SeekingConcentration));
    end
    for j=1:numel(batch)
        records{first+j-1}=batchResults{j};
    end
    writetable(struct2table([records{1:last}]),fullfile(resultDir,'raw_runs_checkpoint.csv'));
    fprintf('Completed %d/%d runs with %d workers\n',last,numel(jobs),workerCount);
end

rawRuns=struct2table([records{:}]);
writetable(rawRuns,fullfile(resultDir,'raw_runs.csv'));
summaryRecords={};
algorithms={'EG','ER','NG','NR'};
labels={'E-G','E-R','N-G','N-R'};
for k=1:numel(algorithms)
    rows=rawRuns(strcmp(rawRuns.Algorithm,labels{k}),:);
    for functionID=functionIDs
        current=rows(rows.FunctionID==functionID,:);
        summaryRecords{end+1}=struct('Function',sprintf('F%02d',functionID), ...
            'FunctionID',functionID,'Algorithm',labels{k},'Runs',height(current), ...
            'MeanError',mean(current.BestError),'StdError',std(current.BestError), ...
            'MedianError',median(current.BestError),'MeanSeconds',mean(current.Seconds), ...
            'SeekingSuccessRate',mean(current.SeekingSuccessRate), ...
            'SeekingGlobalImprovementRate',mean(current.SeekingGlobalImprovementRate), ...
            'DistanceToBestMean',mean(current.DistanceToBestMean), ...
            'DistanceToEliteMean',mean(current.DistanceToEliteMean), ...
            'EliteAlignedFraction',mean(current.EliteAlignedFraction));
    end
end
writetable(struct2table([summaryRecords{:}]),fullfile(resultDir,'summary.csv'));
readme={ ...
    '# Seeking elite guidance x candidate screening interaction at 60k FE', ...
    '', ...
    '- Functions: F3, F6, F9, F12, F13, F20, F28 and F30.', ...
    '- Repeats: 61:63; D=30; population=50; 60,000 FE.', ...
    '- All variants use Range Seeking, tracing decay, virtual tracing with rollback, MR=0.4, SMP=5, 2 Tracing + 3 Seeking FE, no Recovery and no RL.', ...
    '- E-G: Seeking elite guidance enabled + Global-Cap2.', ...
    '- E-R: Seeking elite guidance enabled + Matched-Random.', ...
    '- N-G: Seeking elite guidance disabled (Tracing elite guidance remains enabled) + Global-Cap2.', ...
    '- N-R: Seeking elite guidance disabled + Matched-Random.', ...
    '- The independent `seekingEliteGuidance` switch isolates Seeking guidance from Tracing guidance.', ...
    '- Feedback logs include selected-candidate distances to round-start gbest and sampled elite; no extra Fitness evaluations are used.', ...
    ''};
fid=fopen(fullfile(resultDir,'README.md'),'w');
fprintf(fid,'%s\n',readme{:});
fclose(fid);
delete(gcp('nocreate'))
fprintf('Saved elite-screen interaction experiment to %s\n',resultDir);

function value=CEC2017Function(x,functionID)
    value=cec17_func(x',functionID);
    value=value(1);
end
