clc
clear
close all

root=fileparts(mfilename('fullpath'));
addpath(root,fullfile(root,'data','cec2017'))
cd(fullfile(root,'data','cec2017'))

functionIDs=[3 6 9 12 13 20 28 30];
repeatIDs=51:53;
selectionModes={'globalCap2','g2Random','g2Age'};
algorithmNames={'D3-G3','D3-G2Random','D3-G2Age'};
D=30;
population=50;
maxEvaluations=60000;
seedBase=20271004;
lb=-100*ones(1,D);
ub=100*ones(1,D);
workerCount=4;
batchSize=4;

% Logging-only trajectory audit: enabling feedback logs must not alter T or Best.
rng(seedBase+repeatIDs(1),'twister')
auditInitialPopulation=lb+rand(population,D).*(ub-lb);
f=@(x)CEC2017Function(x,3);
auditState=struct('lowerBound',lb,'upperBound',ub, ...
    'maxEvaluations',6000,'initialPopulation',auditInitialPopulation, ...
    'actionMode','fixed2','rlMode','modeAwareV41','seekingMode','range', ...
    'seekSelection','globalCap2','searchCore','elite','eliteGuidance',true, ...
    'tracingElitistAcceptance',true,'tracingDecay',true,'virtualTracing',true, ...
    'SMP',5,'recoveryEnabled',false,'useModePreserving',true, ...
    'feedbackLogging',false,'ablation',struct('useCatScreen',true, ...
    'useCandidateScreen',true,'useRL',false));
[bestOff,tOff,~]=DSS_RLCSO(f,auditState,ceil(6000/population),population,20371051);
auditState.feedbackLogging=true;
[bestOn,tOn,infoAudit]=DSS_RLCSO(f,auditState,ceil(6000/population),population,20371051);
assert(bestOff.Cost==bestOn.Cost && isequal(tOff,tOn))
assert(numel(infoAudit.FeedbackSeekingAgeFE)>0)
fprintf('Feedback logging audit passed: trajectory unchanged.\n');

stamp=char(datetime('now','Format','yyyyMMdd_HHmmss'));
resultDir=fullfile(root,'results','cec',['cec2017_feedback_gap_pilot_' stamp]);
mkdir(resultDir);

jobs=struct('FunctionID',{},'Run',{},'InitSeed',{},'SearchSeed',{}, ...
    'InitialPopulation',{},'Selection',{},'Algorithm',{});
count=0;
for mode=1:numel(selectionModes)
    for functionID=functionIDs
        for repeat=repeatIDs
            initSeed=seedBase+repeat;
            rng(initSeed,'twister')
            count=count+1;
            jobs(count)=struct('FunctionID',functionID,'Run',repeat, ...
                'InitSeed',initSeed,'SearchSeed',initSeed+100000, ...
                'InitialPopulation',lb+rand(population,D).*(ub-lb), ...
                'Selection',selectionModes{mode},'Algorithm',algorithmNames{mode});
        end
    end
end

pool=gcp('nocreate');
if isempty(pool)
    parpool('local',workerCount);
elseif pool.NumWorkers~=workerCount
    delete(pool);
    parpool('local',workerCount);
end

records=cell(numel(jobs),1);
for first=1:batchSize:numel(jobs)
    last=min(first+batchSize-1,numel(jobs));
    batch=jobs(first:last);
    batchResults=cell(numel(batch),1);
    parfor j=1:numel(batch)
        job=batch(j);
        f=@(x)CEC2017Function(x,job.FunctionID);
        state=struct('lowerBound',lb,'upperBound',ub, ...
            'maxEvaluations',maxEvaluations,'initialPopulation',job.InitialPopulation, ...
            'actionMode','fixed2','rlMode','modeAwareV41','seekingMode','range', ...
            'seekSelection',job.Selection,'searchCore','elite','eliteGuidance',true, ...
            'tracingElitistAcceptance',true,'tracingDecay',true, ...
            'virtualTracing',true,'SMP',5,'recoveryEnabled',false, ...
            'useModePreserving',true,'feedbackLogging',true, ...
            'ablation',struct('useCatScreen',true,'useCandidateScreen',true, ...
                'useRL',false));
        [Best,T,info]=DSS_RLCSO(f,state,ceil(maxEvaluations/population), ...
            population,job.SearchSeed);
        assert(info.Evaluations==maxEvaluations && numel(T)==maxEvaluations)
        assert(all(isfinite(T)) && all(info.EvaluationsPerRound==5))
        assert(all(info.ActualTracingEvaluations==2))
        assert(all(info.ActualSeekingEvaluations==3))
        assert(all(info.BudgetFillRate==1))
        assert(max(abs(info.ModeAllocationError),[],'all')==0)
        assert(max(info.SeekingMaxParentEvaluations)<=2)
        ages=info.FeedbackSeekingAgeFE(:);
        offsets=info.FeedbackSeekingVirtualOffset(:);
        successes=info.FeedbackSeekingSuccess(:);
        globals=info.FeedbackSeekingGlobalImprovement(:);
        oldMask=ages>=50; % 10 complete 5-FE rounds, predeclared diagnostic bin
        recentMask=ages<50;
        functionValue=100*job.FunctionID;
        batchResults{j}=struct('Function',sprintf('F%02d',job.FunctionID), ...
            'FunctionID',job.FunctionID,'Algorithm',job.Algorithm,'Run',job.Run, ...
            'InitSeed',job.InitSeed,'SearchSeed',job.SearchSeed, ...
            'Evaluations',info.Evaluations,'BestCost',Best.Cost, ...
            'BestError',max(0,Best.Cost-functionValue),'Seconds',info.Seconds, ...
            'Error30FE',max(0,T(round(0.3*maxEvaluations))-functionValue), ...
            'Error60FE',max(0,T(round(0.6*maxEvaluations))-functionValue), ...
            'Error80FE',max(0,T(round(0.8*maxEvaluations))-functionValue), ...
            'SeekingEvaluations',numel(ages), ...
            'FeedbackAgeMeanFE',mean(ages),'FeedbackAgeMedianFE',median(ages), ...
            'FeedbackAgeP90FE',PercentileValue(ages,0.90), ...
            'FeedbackAgeMaxFE',max(ages), ...
            'VirtualOffsetMean',mean(offsets),'VirtualOffsetP90',PercentileValue(offsets,0.90), ...
            'SeekingSuccessRate',mean(successes), ...
            'SeekingGlobalImprovementRate',mean(globals), ...
            'OldAgeCount',nnz(oldMask),'OldAgeSuccessRate',SafeMean(successes(oldMask)), ...
            'RecentAgeCount',nnz(recentMask),'RecentAgeSuccessRate',SafeMean(successes(recentMask)), ...
            'MeanParentCoverage',mean(info.SeekingParentCoverage), ...
            'MeanConcentration',mean(info.SeekingConcentration));
    end
    for j=1:numel(batch)
        records{first+j-1}=batchResults{j};
    end
    writetable(struct2table([records{1:last}]),fullfile(resultDir,'raw_runs_checkpoint.csv'));
    fprintf('Completed %d/%d runs with %d workers\n',last,numel(jobs),workerCount);
end

rawRuns=struct2table([records{:}]);
writetable(rawRuns,fullfile(resultDir,'raw_runs.csv'));
summaryRecords={};
for mode=1:numel(selectionModes)
    for functionID=functionIDs
        rows=rawRuns(rawRuns.FunctionID==functionID & ...
            strcmp(rawRuns.Algorithm,algorithmNames{mode}),:);
        summaryRecords{end+1}=struct('Function',sprintf('F%02d',functionID), ...
            'FunctionID',functionID,'Algorithm',algorithmNames{mode}, ...
            'Runs',height(rows),'MeanError',mean(rows.BestError), ...
            'StdError',std(rows.BestError),'MedianError',median(rows.BestError), ...
            'MeanSeconds',mean(rows.Seconds), ...
            'FeedbackAgeMeanFE',mean(rows.FeedbackAgeMeanFE), ...
            'FeedbackAgeP90FE',mean(rows.FeedbackAgeP90FE), ...
            'OldAgeSuccessRate',mean(rows.OldAgeSuccessRate,'omitnan'), ...
            'RecentAgeSuccessRate',mean(rows.RecentAgeSuccessRate,'omitnan'), ...
            'SeekingSuccessRate',mean(rows.SeekingSuccessRate), ...
            'SeekingGlobalImprovementRate',mean(rows.SeekingGlobalImprovementRate));
    end
end
writetable(struct2table([summaryRecords{:}]),fullfile(resultDir,'summary.csv'));
readme={ ...
    '# Feedback-gap pilot at 60k FE', ...
    '', ...
    '- Functions: F3, F6, F9, F12, F13, F20, F28 and F30.', ...
    '- Repeats: 51:53; D=30; population=50; 60,000 FE.', ...
    '- D3 search dynamics are unchanged: Range Seeking, tracing decay, virtual tracing and rollback.', ...
    '- G3: standard Global-Cap2 (2 near-best + 1 far-center).', ...
    '- G2Random: 1 near-best + 1 far-center + one random feedback candidate.', ...
    '- G2Age: 1 near-best + 1 far-center + one candidate from the largest FE feedback age.', ...
    '- G2Random and G2Age use the same candidate generation and parent-cap rule; only the compensation parent selection differs.', ...
    '- The script checks exact FE accounting, 2 Tracing + 3 Seeking allocation and parent cap.', ...
    '- A 6,000-FE logging audit passed with identical Best and T trajectories with logging disabled/enabled.', ...
    '- Age threshold 50 FE is a fixed diagnostic bin (10 five-FE rounds), not a tuned decision threshold.', ...
    ''};
fid=fopen(fullfile(resultDir,'README.md'),'w');
fprintf(fid,'%s\n',readme{:});
fclose(fid);
delete(gcp('nocreate'))
fprintf('Saved feedback-gap pilot to %s\n',resultDir);

function value=SafeMean(x)
    if isempty(x), value=NaN; else, value=mean(x); end
end
function value=PercentileValue(x,p)
    x=sort(x(:));
    value=x(max(1,min(numel(x),ceil(p*numel(x)))));
end
function value=CEC2017Function(x,functionID)
    value=cec17_func(x',functionID);
    value=value(1);
end
